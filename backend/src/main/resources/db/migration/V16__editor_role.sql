-- T25: a second, deliberately limited role. OWNER keeps every right; EDITOR helps with content,
-- guests, RSVP, wishes and reminders but never touches credentials, link/PIN secrets, exports,
-- access policy or import commits. Matrix + threat model: docs/16-editor-role-and-permission-matrix.md.
-- The single-row guarantee of V3 is replaced by a role matrix, so more than one account may exist.
ALTER TABLE admin_users DROP CONSTRAINT admin_users_id_check;
ALTER TABLE admin_users ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(pg_get_serial_sequence('admin_users','id'),(SELECT max(id) FROM admin_users));
ALTER TABLE admin_users
    ADD COLUMN role varchar(20) NOT NULL DEFAULT 'OWNER',
    ADD COLUMN display_name varchar(100) NOT NULL DEFAULT '',
    ADD COLUMN created_by varchar(60),
    ADD CONSTRAINT admin_users_role_check CHECK (role IN ('OWNER','EDITOR')),
    -- Kept permissive on purpose: existing usernames must survive the migration; strict form is enforced by the service.
    ADD CONSTRAINT admin_users_username_check CHECK (char_length(username) BETWEEN 3 AND 60);
CREATE UNIQUE INDEX admin_users_username_unique ON admin_users(lower(username));
-- Actions are attributed to the person who performed them, not just to "the owner".
ALTER TABLE audit ADD COLUMN actor varchar(60) NOT NULL DEFAULT 'owner';
CREATE INDEX audit_actor_idx ON audit(actor,created_at DESC);